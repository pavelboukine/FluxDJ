-- What the signed-in user may do with an invitation. Reveals the event and
-- signer only to the verified intended signer.
create function public.client_invitation_status(p_link_id uuid, p_tenant_slug text)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  i record;
  v_email text;
begin
  if (select auth.uid()) is null then
    return jsonb_build_object('state', 'signed_out');
  end if;
  select * into i from private.contract_invitation(p_link_id, null, p_tenant_slug);
  if not found or not i.usable then
    return jsonb_build_object('state', 'invalid');
  end if;
  v_email := private.current_verified_email();
  if v_email is null then
    return jsonb_build_object('state', 'unverified', 'tenant_display_name', i.tenant_display_name);
  end if;
  if v_email <> lower(i.signer_email) then
    return jsonb_build_object('state', 'wrong_account', 'tenant_display_name', i.tenant_display_name,
      'signed_in_email', v_email, 'intended_email', private.masked_email(i.signer_email));
  end if;
  return jsonb_build_object(
    'state', case when exists (
      select 1 from public.event_access ea where ea.tenant_id = i.tenant_id and ea.event_id = i.event_id
        and ea.user_id = (select auth.uid()) and ea.client_id = i.signer_client_id and ea.revoked_at is null)
      then 'accepted' else 'ready' end,
    'tenant_display_name', i.tenant_display_name, 'event_title', i.event_title, 'signer_name', i.signer_name,
    'contract_id', i.contract_id);
end;
$$;

-- Grants the verified signer access to the event, idempotently, after
-- rechecking everything under the event lock. Never grants planning or books.
create function public.accept_contract_invitation(p_link_id uuid, p_tenant_slug text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  i record;
  v_uid uuid := (select auth.uid());
  v_email text;
  v_existing record;
begin
  if v_uid is null then
    return jsonb_build_object('state', 'signed_out');
  end if;
  select * into i from private.contract_invitation(p_link_id, null, p_tenant_slug);
  if not found then
    return jsonb_build_object('state', 'invalid');
  end if;
  perform 1 from public.events where tenant_id = i.tenant_id and id = i.event_id for update;
  select * into i from private.contract_invitation(p_link_id, null, p_tenant_slug);
  if not i.usable then
    return jsonb_build_object('state', 'invalid');
  end if;
  v_email := private.current_verified_email();
  if v_email is null then
    return jsonb_build_object('state', 'unverified');
  end if;
  if v_email <> lower(i.signer_email) then
    return jsonb_build_object('state', 'wrong_account');
  end if;
  if not exists (select 1 from public.event_clients ec where ec.tenant_id = i.tenant_id and ec.event_id = i.event_id
                 and ec.client_id = i.signer_client_id) then
    return jsonb_build_object('state', 'invalid');
  end if;

  select ea.client_id into v_existing from public.event_access ea
  where ea.tenant_id = i.tenant_id and ea.event_id = i.event_id and ea.user_id = v_uid and ea.revoked_at is null;
  if found and v_existing.client_id <> i.signer_client_id then
    return jsonb_build_object('state', 'invalid');
  end if;
  if not found then
    insert into public.event_access (tenant_id, event_id, client_id, user_id)
    values (i.tenant_id, i.event_id, i.signer_client_id, v_uid);
    perform private.audit(i.tenant_id, 'event', i.event_id, 'client_access_granted', 'client', v_uid,
      jsonb_build_object('contract_id', i.contract_id, 'invitation_id', i.link_id));
  end if;
  update public.access_links set consumed_at = now() where id = i.link_id and consumed_at is null;
  return jsonb_build_object('state', 'accepted', 'contract_id', i.contract_id);
end;
$$;

-- Whether the signed-in user may read this contract right now.
create function private.client_can_read_contract(p_contract_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.contracts c
    join public.events e on e.tenant_id = c.tenant_id and e.id = c.event_id
    join public.tenants t on t.id = c.tenant_id
    join public.proposals p on p.tenant_id = c.tenant_id and p.id = c.proposal_id
    join public.event_access ea on ea.tenant_id = c.tenant_id and ea.event_id = c.event_id
      and ea.user_id = (select auth.uid()) and ea.client_id = c.signer_client_id and ea.revoked_at is null
    where c.id = p_contract_id and c.status = 'sent' and e.archived_at is null and t.archived_at is null
      and p.status = 'approved' and e.active_proposal_id = c.proposal_id
      and lower(c.signer_email) = private.current_verified_email()
  );
$$;
revoke execute on function private.client_can_read_contract(uuid) from public, anon, authenticated;

-- The client's read-only view of a sent contract: an explicit safe DTO of
-- frozen data only. Anything not readable returns {"state":"unavailable"}.
create function public.client_contract_view(p_contract_id uuid, p_tenant_slug text)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  c public.contracts%rowtype;
  t public.tenants%rowtype;
begin
  select k.* into c from public.contracts k join public.tenants tt on tt.id = k.tenant_id
  where k.id = p_contract_id and tt.slug = p_tenant_slug;
  if not found or not private.client_can_read_contract(c.id) then
    return jsonb_build_object('state', 'unavailable');
  end if;
  select * into t from public.tenants where id = c.tenant_id;
  return jsonb_build_object(
    'state', 'available',
    'brand', jsonb_build_object('display_name', t.display_name, 'brand_colors', t.brand_colors),
    'contract', jsonb_build_object(
      'id', c.id, 'sent_at', c.sent_at, 'content_sha256', c.content_sha256, 'rendered_content', c.rendered_content,
      'signer_name', c.signer_name, 'currency', c.currency, 'total_cents', c.total_cents,
      'deposit_percent', c.deposit_percent, 'deposit_cents', c.deposit_cents, 'balance_cents', c.balance_cents,
      'balance_due_date', c.balance_due_date,
      'event_title', c.party_snapshot -> 'event' ->> 'title', 'event_date', c.party_snapshot -> 'event' ->> 'date',
      'legal_name', coalesce(c.party_snapshot -> 'business' ->> 'legal_name', c.party_snapshot -> 'business' ->> 'name'))
  );
end;
$$;

-- Contracts the signed-in client can read (client home).
create function public.my_contracts()
returns table (tenant_slug text, tenant_display_name text, contract_id uuid, event_title text, event_date text, sent_at timestamptz)
language sql
stable
security definer
set search_path = ''
as $$
  select t.slug, t.display_name, c.id, c.party_snapshot -> 'event' ->> 'title', c.party_snapshot -> 'event' ->> 'date', c.sent_at
  from public.contracts c
  join public.tenants t on t.id = c.tenant_id
  join public.event_access ea on ea.tenant_id = c.tenant_id and ea.event_id = c.event_id
    and ea.user_id = (select auth.uid()) and ea.revoked_at is null
  where c.status = 'sent' and private.client_can_read_contract(c.id)
  order by c.sent_at desc;
$$;

