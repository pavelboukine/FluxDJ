create function private.issue_contract_invitation(c public.contracts, p_link_id uuid, p_token_hash text)
returns timestamptz
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_expires timestamptz := now() + interval '14 days';
begin
  if p_link_id is null or p_token_hash is null or p_token_hash !~ '^[0-9a-f]{64}$' then
    raise exception 'invalid access link' using errcode = 'invalid_parameter_value';
  end if;
  insert into public.access_links (id, tenant_id, purpose, proposal_id, contract_id, intended_client_id, token_hash, expires_at)
  values (p_link_id, c.tenant_id, 'contract', c.proposal_id, c.id, c.signer_client_id, p_token_hash, v_expires);
  perform private.enqueue_contract_email(
    c.tenant_id, 'contract_sent', c.signer_email, c.id, p_link_id,
    jsonb_build_object(
      'client_name', c.signer_name,
      'event_title', c.party_snapshot -> 'event' ->> 'title',
      'legal_name', coalesce(c.party_snapshot -> 'business' ->> 'legal_name', c.party_snapshot -> 'business' ->> 'name'),
      'contact_email', c.party_snapshot -> 'business' ->> 'contact_email',
      'deposit_cents', c.deposit_cents, 'deposit_percent', c.deposit_percent, 'currency', c.currency,
      'invitation_expires_at', v_expires),
    'contract_sent:' || p_link_id);
  return v_expires;
end;
$$;
revoke execute on function private.issue_contract_invitation(public.contracts, uuid, text) from public, anon, authenticated;

-- Sends the current eligible draft. Repeats (including concurrent ones, which
-- wait on the event lock) return the existing result without new links or
-- emails. The event stays awaiting_signature; nothing is booked.
create function public.send_contract(p_contract_id uuid, p_link_id uuid, p_token_hash text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  c public.contracts%rowtype;
  v_problems jsonb;
  v_expires timestamptz;
begin
  c := private.lock_contract_for_staff(p_contract_id);
  if c.status = 'sent' then
    return jsonb_build_object('status', 'sent', 'replayed', true, 'contract_id', c.id, 'sent_at', c.sent_at,
      'recipient_email', c.signer_email);
  end if;
  v_problems := private.contract_send_problems(c.id);
  if c.status <> 'draft' then
    raise exception 'contract_not_sendable: this contract is %', c.status using errcode = 'invalid_parameter_value';
  end if;
  if jsonb_array_length(v_problems) > 0 then
    raise exception 'contract_not_sendable: %', private.contract_problem_text(v_problems) using errcode = 'invalid_parameter_value';
  end if;

  perform set_config('flux.sending_contract', c.id::text, true);
  update public.contracts set status = 'sent' where id = c.id returning * into c;
  perform set_config('flux.sending_contract', '', true);
  v_expires := private.issue_contract_invitation(c, p_link_id, p_token_hash);
  perform private.audit(c.tenant_id, 'contract', c.id, 'sent', 'staff', (select auth.uid()),
    jsonb_build_object('invitation_id', p_link_id, 'content_sha256', c.content_sha256));
  return jsonb_build_object('status', 'sent', 'replayed', false, 'contract_id', c.id, 'sent_at', c.sent_at,
    'recipient_email', c.signer_email, 'invitation_expires_at', v_expires);
end;
$$;

-- Resends an unchanged sent contract with a fresh invitation. Earlier
-- invitations are revoked and their pending emails cancelled; sent_at,
-- content, hashes and any event access already granted are untouched.
-- Rate limited: one resend per 2 minutes and 10 per day per contract.
create function public.resend_contract(p_contract_id uuid, p_link_id uuid, p_token_hash text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  c public.contracts%rowtype;
  v_problems jsonb;
  v_expires timestamptz;
begin
  c := private.lock_contract_for_staff(p_contract_id);
  if c.status <> 'sent' then
    raise exception 'contract_not_resendable: only a sent, unsigned contract can be resent (this one is %)', c.status
      using errcode = 'invalid_parameter_value';
  end if;
  v_problems := private.contract_send_problems(c.id);
  if jsonb_array_length(v_problems) > 0 then
    raise exception 'contract_not_sendable: %', private.contract_problem_text(v_problems) using errcode = 'invalid_parameter_value';
  end if;
  if exists (select 1 from public.access_links l where l.purpose = 'contract' and l.contract_id = c.id
             and l.created_at > now() - interval '2 minutes')
     or (select count(*) from public.access_links l where l.purpose = 'contract' and l.contract_id = c.id
         and l.created_at > now() - interval '1 day') >= 10 then
    raise exception 'contract_resend_too_soon: this contract was sent very recently. Wait a few minutes before resending'
      using errcode = 'invalid_parameter_value';
  end if;

  perform private.retire_contract_invitations(c.id, 'replaced by a resend');
  v_expires := private.issue_contract_invitation(c, p_link_id, p_token_hash);
  perform private.audit(c.tenant_id, 'contract', c.id, 'resent', 'staff', (select auth.uid()), jsonb_build_object('invitation_id', p_link_id));
  return jsonb_build_object('status', 'sent', 'contract_id', c.id, 'sent_at', c.sent_at, 'recipient_email', c.signer_email,
    'invitation_expires_at', v_expires);
end;
$$;

-- Voids an unsigned sent contract. Content and history are kept; invitations
-- are revoked and pending contract emails cancelled; clients can no longer
-- read it. Event access, other events and Auth identities are untouched. A
-- replacement draft can then be generated from the current approval.
create function public.void_contract(p_contract_id uuid, p_reason text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  c public.contracts%rowtype;
begin
  if p_reason is null or length(btrim(p_reason)) not between 1 and 500 then
    raise exception 'contract_void_invalid: give a reason (up to 500 characters)' using errcode = 'invalid_parameter_value';
  end if;
  c := private.lock_contract_for_staff(p_contract_id);
  if c.status = 'void' then
    return jsonb_build_object('status', 'void', 'replayed', true);
  end if;
  if c.status <> 'sent' then
    raise exception 'contract_void_invalid: only a sent, unsigned contract can be voided (this one is %)', c.status
      using errcode = 'invalid_parameter_value';
  end if;
  update public.contracts set status = 'void', void_reason = btrim(p_reason) where id = c.id;
  perform private.retire_contract_invitations(c.id, 'contract voided');
  perform private.audit(c.tenant_id, 'contract', c.id, 'voided', 'staff', (select auth.uid()), jsonb_build_object('reason', btrim(p_reason)));
  return jsonb_build_object('status', 'void', 'replayed', false);
end;
$$;

