-- What an invitation (by id or token hash) currently allows. Shared checks.
create function private.contract_invitation(p_link_id uuid, p_token_hash text, p_tenant_slug text)
returns table (usable boolean, link_id uuid, tenant_id uuid, tenant_display_name text, contract_id uuid, event_id uuid,
               signer_client_id uuid, signer_email text, signer_name text, event_title text)
language sql
stable
security definer
set search_path = ''
as $$
  select (l.revoked_at is null and l.expires_at > now() and t.archived_at is null and c.status = 'sent'
          and e.archived_at is null and p.status = 'approved' and e.active_proposal_id = c.proposal_id),
         l.id, l.tenant_id, t.display_name, c.id, c.event_id, c.signer_client_id, c.signer_email, c.signer_name,
         c.party_snapshot -> 'event' ->> 'title'
  from public.access_links l
  join public.tenants t on t.id = l.tenant_id
  join public.contracts c on c.tenant_id = l.tenant_id and c.id = l.contract_id
  join public.events e on e.tenant_id = c.tenant_id and e.id = c.event_id
  join public.proposals p on p.tenant_id = c.tenant_id and p.id = c.proposal_id
  where l.purpose = 'contract' and t.slug = p_tenant_slug
    and ((p_link_id is not null and l.id = p_link_id) or (p_token_hash is not null and l.token_hash = p_token_hash));
$$;
revoke execute on function private.contract_invitation(uuid, text, text) from public, anon, authenticated;

-- Queues a verification email to the frozen signer address. The invitation
-- token only authorizes this; it never signs anyone in. At most 3 requests
-- per invitation per 15 minutes (the app also limits per IP).
create function public.request_contract_sign_in(p_token_hash text, p_tenant_slug text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  i record;
begin
  if p_token_hash is null or p_token_hash !~ '^[0-9a-f]{64}$' then
    return jsonb_build_object('status', 'invalid');
  end if;
  select * into i from private.contract_invitation(null, p_token_hash, p_tenant_slug);
  if not found or not i.usable then
    return jsonb_build_object('status', 'invalid');
  end if;
  perform 1 from public.access_links where id = i.link_id for update;
  if (select count(*) from public.email_outbox o
      where o.access_link_id = i.link_id and o.event_type = 'contract_sign_in' and o.created_at > now() - interval '15 minutes') >= 3 then
    return jsonb_build_object('status', 'rate_limited');
  end if;
  perform private.enqueue_contract_email(i.tenant_id, 'contract_sign_in', i.signer_email, i.contract_id, i.link_id,
    jsonb_build_object('client_name', i.signer_name, 'event_title', i.event_title),
    'contract_sign_in:' || i.link_id || ':' || gen_random_uuid());
  perform private.audit(i.tenant_id, 'contract', i.contract_id, 'sign_in_requested', 'client', null, jsonb_build_object('invitation_id', i.link_id));
  return jsonb_build_object('status', 'ok', 'masked_email', private.masked_email(i.signer_email),
    'tenant_display_name', i.tenant_display_name);
end;
$$;

