-- Contract sending and verified client access (read-only; no signing yet).
--
-- Flow and responsibilities:
--   1. Staff send (send_contract): one transaction locks event, proposal and
--      contract, re-runs private.contract_send_problems, marks the contract
--      sent (sent_at stamped once by the database), creates an expiring
--      contract invitation in access_links (purpose 'contract', scoped to the
--      tenant, event, contract and frozen signer), queues the contract email
--      and writes an audit record. Repeats return the existing result.
--   2. The invitation token is derived on the server as
--      HMAC(PROPOSAL_LINK_SECRET, "flux:contract-invite:v1:" + link id); only
--      sha256(token) is stored. It authorizes exactly one thing: asking for a
--      verification email to the frozen signer address
--      (request_contract_sign_in). It is never proof of identity.
--   3. The verification email's Supabase link is generated by the outbox
--      worker at delivery time (Auth admin API) and never stored.
--   4. After the client verifies their email through Supabase Auth and
--      confirms, accept_contract_invitation grants event access, idempotently,
--      to the exact tenant, event and signer client, and only if the verified
--      email matches the frozen signer email.
--   5. client_contract_view returns a safe DTO of the frozen contract after
--      rechecking identity, access, signer and eligibility on every read.
--
-- Resend replaces the invitation (old one revoked, pending emails cancelled);
-- void ends an unsigned sent contract. Signing is not implemented: no status
-- can reach 'signed'.

