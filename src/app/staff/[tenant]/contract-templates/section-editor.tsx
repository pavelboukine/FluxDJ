"use client";

import { useEffect, useId, useLayoutEffect, useMemo, useRef, useState, type KeyboardEvent } from "react";
import { ArrowDown, ArrowUp, Braces, Plus, Trash2, X } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { fieldClass } from "@/components/app/list";
import { ContractDocument } from "@/components/contract/contract-document";
import { fillExamples, groupFields, MULTILINE_FIELDS, scanPlaceholders, type CatalogField } from "@/lib/contracts/fields";
import { LIMITS, sectionProblem, type TemplateSection } from "@/lib/contracts/template-text";
import { cn } from "@/lib/utils";

type Section = TemplateSection & { id: string };

type Props = {
  initialTitle: string;
  initialSections: readonly TemplateSection[];
  /** The placeholder catalog (contract_placeholder_catalog). */
  fields: CatalogField[];
  /** Values shown in the preview instead of fields: examples, plus the business's own details where known. */
  exampleValues: Record<string, string>;
};

/**
 * The contract template editor: the document title and its sections, each a
 * heading and plain text, with Add / Move / Remove and an Insert field menu
 * that puts a {{field}} at the cursor. It renders named inputs ("title",
 * "heading", "body", in document order) inside the surrounding ActionForm,
 * which saves them with the usual version check and unsaved-changes tracking.
 * Beside it (or behind an Edit / Preview switch on small screens), the draft
 * as the client reads it, through the same ContractDocument, with example
 * values in place of fields. Nothing is saved or generated by previewing.
 */
export function SectionEditor({ initialTitle, initialSections, fields, exampleValues }: Props) {
  const [title, setTitle] = useState(initialTitle);
  const [sections, setSections] = useState<Section[]>(() =>
    (initialSections.length ? initialSections : [{ heading: "", body: "" }]).map((s, i) => ({ ...s, id: `s${i}` })),
  );
  const [view, setView] = useState<"edit" | "preview">("edit");
  const [menuFor, setMenuFor] = useState<string | null>(null);
  const nextId = useRef(0);
  const root = useRef<HTMLDivElement>(null);
  const textareas = useRef(new Map<string, HTMLTextAreaElement>());
  const selections = useRef(new Map<string, { start: number; end: number }>());
  const known = useMemo(() => new Set(fields.map((f) => f.key)), [fields]);

  // Structural changes (add, move, remove, insert) don't fire input events; tell the form so it can track unsaved edits.
  const [structureTick, setStructureTick] = useState(0);
  useEffect(() => {
    if (structureTick === 0) return;
    root.current?.closest("form")?.dispatchEvent(new Event("input", { bubbles: true }));
  }, [structureTick]);
  const touched = () => setStructureTick((n) => n + 1);

  function update(id: string, patch: Partial<TemplateSection>) {
    setSections((list) => list.map((s) => (s.id === id ? { ...s, ...patch } : s)));
  }
  function add(after: number) {
    const id = `n${nextId.current++}`;
    setSections((list) => [...list.slice(0, after + 1), { id, heading: "", body: "" }, ...list.slice(after + 1)]);
    touched();
    window.requestAnimationFrame(() => document.getElementById(`heading-${id}`)?.focus());
  }
  function move(index: number, by: -1 | 1) {
    setSections((list) => {
      const next = [...list];
      [next[index], next[index + by]] = [next[index + by], next[index]];
      return next;
    });
    touched();
  }
  function remove(index: number) {
    const s = sections[index];
    const name = s.heading.trim() || `section ${index + 1}`;
    if ((s.heading.trim() || s.body.trim()) && !window.confirm(`Remove "${name}" and its text from this draft? Published versions keep theirs.`)) return;
    setSections((list) => list.filter((_, i) => i !== index));
    touched();
  }
  function remember(id: string, el: HTMLTextAreaElement) {
    selections.current.set(id, { start: el.selectionStart, end: el.selectionEnd });
  }
  function insert(section: Section, key: string) {
    const at = selections.current.get(section.id) ?? { start: section.body.length, end: section.body.length };
    const before = section.body.slice(0, at.start);
    const after = section.body.slice(at.end);
    let token = `{{${key}}}`;
    // List fields read best on their own line.
    if (MULTILINE_FIELDS.has(key)) {
      if (before && !before.endsWith("\n")) token = `\n${token}`;
      if (after && !after.startsWith("\n")) token = `${token}\n`;
    }
    const caret = before.length + token.length;
    update(section.id, { body: before + token + after });
    selections.current.set(section.id, { start: caret, end: caret });
    setMenuFor(null);
    touched();
    window.requestAnimationFrame(() => {
      const el = textareas.current.get(section.id);
      el?.focus();
      el?.setSelectionRange(caret, caret);
    });
  }

  const scan = useMemo(() => scanPlaceholders([title, ...sections.flatMap((s) => [s.heading, s.body])].join("\n"), known), [title, sections, known]);
  const preview = (
    <div className="grid gap-3">
      <p className="rounded-lg border border-sky-600/40 bg-sky-600/10 p-3 text-sm" data-testid="preview-note">
        <span className="font-medium">Preview with example values.</span> Fields show example details (your business details where they&apos;re
        set). A real contract fills in the client, event and approved prices when it&apos;s generated. The signed PDF also adds the parties, the
        event, the price table with deposit and balance, the client&apos;s signature and the signing record.
      </p>
      {scan.unknown.length || scan.malformed.length ? (
        <p role="status" className="rounded-lg border border-amber-500/50 bg-amber-500/10 p-3 text-sm">
          Not a field: {[...scan.unknown.map((k) => `{{${k}}}`), ...scan.malformed.map((m) => `“${m}”`)].join(", ")}. Saving is refused until it&apos;s
          fixed: use Insert field, or remove the braces.
        </p>
      ) : null}
      <div className="rounded-xl border bg-card p-4 sm:p-6" data-testid="contract-preview">
        <ContractDocument
          title={fillExamples(title, known, exampleValues) || "Untitled agreement"}
          sections={sections.map((s) => ({ heading: fillExamples(s.heading, known, exampleValues), body: fillExamples(s.body, known, exampleValues) }))}
          headingLevel={2}
          label="Draft preview"
        />
      </div>
    </div>
  );

  return (
    <div ref={root} className="grid gap-4">
      <div className="flex gap-1 rounded-lg border p-1 lg:hidden" role="group" aria-label="Editor view">
        {(["edit", "preview"] as const).map((v) => (
          <Button key={v} type="button" size="sm" variant={view === v ? "secondary" : "ghost"} aria-pressed={view === v} className="flex-1" onClick={() => setView(v)}>
            {v === "edit" ? "Edit" : "Preview"}
          </Button>
        ))}
      </div>
      <div className="grid gap-6 lg:grid-cols-[minmax(0,1fr)_minmax(0,1fr)] lg:items-start">
        <div className={cn("grid min-w-0 gap-4", view === "preview" && "max-lg:hidden")}>
          <div className="grid gap-1.5">
            <Label htmlFor="contract-title">Document title</Label>
            <Input id="contract-title" name="title" required maxLength={LIMITS.title} value={title} onChange={(e) => setTitle(e.target.value)} />
            <p className="text-xs text-muted-foreground">One line. Fields work here too, for example the event title.</p>
          </div>
          <ol className="grid gap-4" aria-label="Sections">
            {sections.map((s, i) => {
              const problem = sectionProblem(s);
              const label = s.heading.trim() || `section ${i + 1}`;
              return (
                <li key={s.id} className="grid min-w-0 gap-2 rounded-xl border bg-card p-3 sm:p-4" data-testid="section-card">
                  <div className="flex flex-wrap items-center justify-between gap-2">
                    <span className="text-xs font-medium text-muted-foreground">Section {i + 1}</span>
                    <div className="flex items-center gap-1">
                      <Button type="button" size="icon-sm" variant="ghost" aria-label={`Move ${label} up`} disabled={i === 0} onClick={() => move(i, -1)}>
                        <ArrowUp aria-hidden />
                      </Button>
                      <Button type="button" size="icon-sm" variant="ghost" aria-label={`Move ${label} down`} disabled={i === sections.length - 1} onClick={() => move(i, 1)}>
                        <ArrowDown aria-hidden />
                      </Button>
                      <Button type="button" size="icon-sm" variant="ghost" aria-label={`Remove ${label}`} disabled={sections.length === 1} onClick={() => remove(i)}>
                        <Trash2 aria-hidden />
                      </Button>
                    </div>
                  </div>
                  <Input
                    id={`heading-${s.id}`}
                    name="heading"
                    value={s.heading}
                    maxLength={LIMITS.heading}
                    placeholder="Heading, for example Payment"
                    aria-label={`Heading of section ${i + 1}`}
                    className="font-semibold"
                    onChange={(e) => update(s.id, { heading: e.target.value })}
                  />
                  <BodyField
                    section={s}
                    index={i}
                    register={(el) => (el ? textareas.current.set(s.id, el) : textareas.current.delete(s.id))}
                    onChange={(body) => update(s.id, { body })}
                    onSelect={(el) => remember(s.id, el)}
                  />
                  <div className="flex flex-wrap items-center gap-2">
                    <Button type="button" size="sm" variant="outline" aria-expanded={menuFor === s.id} aria-controls={`fields-${s.id}`} onClick={() => setMenuFor(menuFor === s.id ? null : s.id)}>
                      <Braces aria-hidden />
                      Insert field
                    </Button>
                    <Button type="button" size="sm" variant="ghost" onClick={() => add(i)} aria-label={`Add a section after ${label}`}>
                      <Plus aria-hidden />
                      Add section below
                    </Button>
                    {s.body.length > LIMITS.body * 0.9 ? (
                      <span className="text-xs text-muted-foreground">{s.body.length.toLocaleString("en-CA")} / {LIMITS.body.toLocaleString("en-CA")}</span>
                    ) : null}
                  </div>
                  {menuFor === s.id ? (
                    <FieldMenu
                      id={`fields-${s.id}`}
                      fields={fields}
                      sectionLabel={label}
                      onPick={(key) => insert(s, key)}
                      onClose={() => {
                        setMenuFor(null);
                        textareas.current.get(s.id)?.focus();
                      }}
                    />
                  ) : null}
                  {problem ? <p className="text-xs text-amber-700 dark:text-amber-400" data-testid="section-problem">{problem}</p> : null}
                </li>
              );
            })}
          </ol>
          <div>
            <Button type="button" variant="outline" onClick={() => add(sections.length - 1)} disabled={sections.length >= LIMITS.sections}>
              <Plus aria-hidden />
              Add section
            </Button>
          </div>
        </div>
        <div className={cn("min-w-0 lg:sticky lg:top-20", view === "edit" && "max-lg:hidden")}>
          <h2 className="mb-2 text-base font-semibold">Preview</h2>
          {preview}
        </div>
      </div>
    </div>
  );
}

function BodyField({ section, index, register, onChange, onSelect }: {
  section: Section;
  index: number;
  register: (el: HTMLTextAreaElement | null) => void;
  onChange: (body: string) => void;
  onSelect: (el: HTMLTextAreaElement) => void;
}) {
  const ref = useRef<HTMLTextAreaElement | null>(null);
  // Grows with its text, so a section reads like part of the document (no scrolling inside it).
  useLayoutEffect(() => {
    const el = ref.current;
    if (!el) return;
    el.style.height = "auto";
    el.style.height = `${el.scrollHeight + 2}px`;
  }, [section.body]);
  return (
    <textarea
      ref={(el) => {
        ref.current = el;
        register(el);
      }}
      name="body"
      value={section.body}
      rows={4}
      aria-label={`Text of section ${index + 1}`}
      placeholder="The section's text. Line breaks are kept exactly as typed."
      className={cn(fieldClass, "min-h-24 w-full resize-none py-2 leading-relaxed")}
      onChange={(e) => {
        onChange(e.target.value);
        onSelect(e.target);
      }}
      onSelect={(e) => onSelect(e.currentTarget)}
      onKeyUp={(e) => onSelect(e.currentTarget)}
      onClick={(e) => onSelect(e.currentTarget)}
      onBlur={(e) => onSelect(e.currentTarget)}
    />
  );
}

/** Supported fields, grouped and searchable; picking one inserts it where the cursor was. */
function FieldMenu({ id, fields, sectionLabel, onPick, onClose }: {
  id: string;
  fields: CatalogField[];
  sectionLabel: string;
  onPick: (key: string) => void;
  onClose: () => void;
}) {
  const [query, setQuery] = useState("");
  const searchId = useId();
  const q = query.trim().toLowerCase();
  const groups = groupFields(q ? fields.filter((f) => `${f.label} ${f.key} ${f.description}`.toLowerCase().includes(q)) : fields);
  const search = useRef<HTMLInputElement>(null);
  useEffect(() => search.current?.focus(), []);
  const onKeyDown = (e: KeyboardEvent) => {
    if (e.key === "Escape") {
      e.preventDefault();
      onClose();
    }
  };
  return (
    <div id={id} role="group" aria-label={`Insert a field into ${sectionLabel}`} className="grid gap-3 rounded-lg border bg-muted/30 p-3" onKeyDown={onKeyDown}>
      <div className="flex items-end gap-2">
        <label htmlFor={searchId} className="grid flex-1 gap-1 text-xs font-medium text-muted-foreground">
          Find a field
          <input
            ref={search}
            id={searchId}
            type="search"
            value={query}
            onChange={(e) => setQuery(e.target.value)}
            onKeyDown={(e) => {
              // Enter picks the first match instead of submitting the form.
              if (e.key === "Enter") {
                e.preventDefault();
                const first = groups[0]?.fields[0];
                if (first) onPick(first.key);
              }
            }}
            placeholder="Client name, total, date…"
            className={cn(fieldClass, "text-foreground")}
          />
        </label>
        <Button type="button" size="icon-sm" variant="ghost" aria-label="Close the field list" onClick={onClose}>
          <X aria-hidden />
        </Button>
      </div>
      {groups.length === 0 ? <p className="text-sm text-muted-foreground">No field matches. Only these fields can be filled in automatically.</p> : null}
      {groups.map((g) => (
        <div key={g.label} className="grid gap-1">
          <p className="text-xs font-semibold tracking-wide text-muted-foreground uppercase">{g.label}</p>
          <ul className="grid gap-1 sm:grid-cols-2">
            {g.fields.map((f) => (
              <li key={f.key}>
                <button
                  type="button"
                  onClick={() => onPick(f.key)}
                  className="grid w-full gap-0.5 rounded-md border bg-card px-2.5 py-2 text-left text-sm outline-none hover:bg-muted focus-visible:ring-3 focus-visible:ring-ring/50"
                >
                  <span className="font-medium">{f.label}</span>
                  <span className="text-xs text-muted-foreground">{f.description}</span>
                  <code className="text-xs text-muted-foreground [overflow-wrap:anywhere]">{`{{${f.key}}}`}</code>
                  {MULTILINE_FIELDS.has(f.key) ? <span className="text-xs text-muted-foreground">A list: inserted on its own line.</span> : null}
                </button>
              </li>
            ))}
          </ul>
        </div>
      ))}
    </div>
  );
}
