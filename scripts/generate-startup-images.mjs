// Generates the installed iPhone app's launch images: the "Flux" wordmark
// from assets/brand (never redrawn), centred on white, the app's own
// background (manifest background_color, the top bar), so launch goes from
// this image straight to the app without a colour change. iOS shows the image
// matching the screen while it starts the app, until the first page paints;
// without one it shows a blank screen. Run with
// `node scripts/generate-startup-images.mjs`; the images and the generated
// list (src/lib/pwa-startup-images.ts) are committed, so builds never run it.
//
// iOS picks an image only by an exact media query (screen size in CSS
// pixels, pixel ratio, orientation), so each iPhone size has its own file.
// Portrait only: the app opens in portrait from the Home Screen.
import sharp from "sharp";
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";

const SOURCE = path.join("assets", "brand", "flux-wordmark-black.png");
const BACKGROUND = { r: 255, g: 255, b: 255, alpha: 1 };
// Wordmark height in CSS pixels: a calm mark, larger than the 20 px top-bar wordmark.
const WORDMARK_CSS_HEIGHT = 40;

// [CSS width, CSS height, device pixel ratio]: iPhone screens from the SE to the 17 Pro Max.
const IPHONES = [
  [320, 568, 2], // SE (1st generation)
  [375, 667, 2], // 6, 7, 8, SE (2nd and 3rd generation)
  [414, 736, 3], // 6 Plus, 7 Plus, 8 Plus
  [375, 812, 3], // X, XS, 11 Pro, 12 mini, 13 mini
  [414, 896, 2], // XR, 11
  [414, 896, 3], // XS Max, 11 Pro Max
  [390, 844, 3], // 12, 12 Pro, 13, 13 Pro, 14, 16e
  [428, 926, 3], // 12 Pro Max, 13 Pro Max, 14 Plus
  [393, 852, 3], // 14 Pro, 15, 15 Pro, 16
  [430, 932, 3], // 14 Pro Max, 15 Plus, 15 Pro Max, 16 Plus
  [402, 874, 3], // 16 Pro, 17, 17 Pro
  [420, 912, 3], // Air
  [440, 956, 3], // 16 Pro Max, 17 Pro Max
];

const trimmed = await sharp(SOURCE).trim({ threshold: 1 }).toBuffer({ resolveWithObject: true });
const outDir = path.join("public", "startup");
rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const entries = [];
for (const [cssWidth, cssHeight, ratio] of IPHONES) {
  const width = cssWidth * ratio;
  const height = cssHeight * ratio;
  const markHeight = WORDMARK_CSS_HEIGHT * ratio;
  if (markHeight > trimmed.info.height) console.warn(`Note: the wordmark is upscaled for ${width} x ${height}`);
  const mark = await sharp(trimmed.data).resize({ height: markHeight, kernel: "lanczos3" }).png().toBuffer({ resolveWithObject: true });
  const image = await sharp({ create: { width, height, channels: 4, background: BACKGROUND } })
    .composite([{ input: mark.data, left: Math.round((width - mark.info.width) / 2), top: Math.round((height - mark.info.height) / 2) }])
    .removeAlpha()
    .png({ compressionLevel: 9, adaptiveFiltering: true, palette: true })
    .toBuffer();
  const file = `launch-${width}x${height}.png`;
  writeFileSync(path.join(outDir, file), image);
  entries.push({
    url: `/startup/${file}`,
    media: `screen and (device-width: ${cssWidth}px) and (device-height: ${cssHeight}px) and (-webkit-device-pixel-ratio: ${ratio}) and (orientation: portrait)`,
  });
  console.log(file, image.length, "bytes");
}

const list = `// Generated by scripts/generate-startup-images.mjs; do not edit by hand.
// The installed iPhone app's launch images (public/startup), one per screen size.
export const STARTUP_IMAGES = ${JSON.stringify(entries, null, 2)};
`;
writeFileSync(path.join("src", "lib", "pwa-startup-images.ts"), list);
console.log(readdirSync(outDir).length, "launch images; list in src/lib/pwa-startup-images.ts");
