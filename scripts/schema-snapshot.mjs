// The generated schema snapshot (supabase/schema-snapshot.sql): the current
// public and private schemas of the LOCAL database, schema only, no data.
// A reading aid; supabase/migrations stays the source of truth.
//
//   pnpm db:schema         rewrite the snapshot from the local database
//   pnpm db:schema:check   exit 1 if the snapshot or src/lib/supabase/database.types.ts
//                          differs from the local database (CI runs this on a fresh replay)
//
// Read-only on the database: `supabase db dump --local` and
// `supabase gen types --local` never change it.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const SNAPSHOT = "supabase/schema-snapshot.sql";
const TYPES = "src/lib/supabase/database.types.ts";
const HEADER = `-- GENERATED by \`pnpm db:schema\` from a local database with every migration applied.
-- Schema only (public and private; Storage policies live in the migrations), no data.
-- A reading aid: supabase/migrations is authoritative. Never edit or apply this file.

`;

const supabase = (args, opts = {}) => execFileSync("node_modules/.bin/supabase", args, { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"], ...opts });

const dir = mkdtempSync(join(tmpdir(), "flux-schema-"));
try {
  const dumpFile = join(dir, "dump.sql");
  supabase(["db", "dump", "--local", "--schema", "public,private", "-f", dumpFile]);
  const snapshot = HEADER + readFileSync(dumpFile, "utf8");

  if (!process.argv.includes("--check")) {
    writeFileSync(SNAPSHOT, snapshot);
    console.log(`Wrote ${SNAPSHOT}.`);
  } else {
    const types = supabase(["gen", "types", "typescript", "--local", "--schema", "public"], { maxBuffer: 64 * 1024 * 1024 });
    const stale = [];
    for (const [file, fresh, fix] of [
      [SNAPSHOT, snapshot, "pnpm db:schema"],
      [TYPES, types, "pnpm db:types"],
    ]) {
      let current = "";
      try {
        current = readFileSync(file, "utf8");
      } catch {
        // Missing counts as stale.
      }
      if (current === fresh) continue;
      const freshFile = join(dir, file.replaceAll("/", "_"));
      writeFileSync(freshFile, fresh);
      try {
        execFileSync("git", ["diff", "--no-index", "--stat", "--", file, freshFile], { stdio: "inherit" });
        execFileSync("git", ["diff", "--no-index", "--", file, freshFile], { stdio: "inherit" });
      } catch {
        // git diff exits 1 when the files differ; the diff is already printed.
      }
      stale.push(`${file} (run \`${fix}\`)`);
    }
    if (stale.length) {
      console.error(`Out of date with the migrations: ${stale.join(", ")}. Regenerate against a local database with every migration applied, then commit.`);
      process.exit(1);
    }
    console.log(`${SNAPSHOT} and ${TYPES} match the database.`);
  }
} finally {
  rmSync(dir, { recursive: true, force: true });
}
